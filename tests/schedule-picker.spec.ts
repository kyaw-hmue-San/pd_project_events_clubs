import { expect, test, webkit, type Browser } from '@playwright/test'

async function verifyPickers(browser: Browser, engine: string) {
  const context = await browser.newContext({ timezoneId: 'America/New_York' })
  const page = await context.newPage()
  const browserErrors: string[] = []
  page.on('pageerror', error => browserErrors.push(error.message))
  await context.addInitScript(engine => {
    // Feature detection can succeed even when opening the native UI does not.
    const state = window as unknown as { nativePickerCalls: number }
    state.nativePickerCalls = 0
    Object.defineProperty(HTMLInputElement.prototype, 'showPicker', { configurable: true, value() { state.nativePickerCalls++; if (engine === 'webkit') throw new DOMException('Native picker unavailable', 'NotSupportedError') } })
  }, engine)
  await context.route('https://unpkg.com/**', route => route.abort())
  await context.route('https://fonts.googleapis.com/**', route => route.abort())
  let creates = 0
  page.on('request', request => { if (request.url().endsWith('/api/activities') && request.method() === 'POST') creates++ })
  try {
    await page.goto('/')
    const opening = page.waitForEvent('popup')
    await page.getByRole('button', { name: 'Continue with Google', exact: true }).click()
    const popup = await opening
    await popup.waitForLoadState('domcontentloaded')
    await popup.getByRole('button', { name: 'Add new account', exact: true }).click()
    await popup.locator('#email-input').fill('e2e.organizer@lamduan.mfu.ac.th')
    await popup.locator('#sign-in').click()
    await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Switch workspace, current Student', exact: true }).click()
    await page.getByRole('button', { name: 'Organizer workspace', exact: true }).click()
    await page.getByRole('navigation').getByRole('button', { name: 'Create activity', exact: true }).click()
    await page.getByLabel('Activity title', { exact: true }).fill(`Picker verification ${engine}`)
    await page.getByLabel('Description', { exact: true }).fill('A schedule selected through the visible calendar and clock controls.')
    await page.getByLabel('Location', { exact: true }).fill('Picker Test Hall')
    await page.getByLabel('Date', { exact: true }).fill('2028-01-31')
    const calendarIcon = page.getByRole('button', { name: 'Open calendar', exact: true })
    await calendarIcon.click()
    let dialog = page.getByRole('dialog', { name: 'Choose date', exact: true })
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).focus()
    await page.keyboard.press('Tab')
    await expect(dialog.getByRole('button', { name: 'Close dialog', exact: true })).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
    await dialog.getByRole('button', { name: 'Next month', exact: true }).click()
    await dialog.getByRole('button', { name: '29 February 2028', exact: true }).click()
    await expect(page.getByLabel('Date', { exact: true })).toHaveValue('2028-02-29')
    await expect(calendarIcon).toBeFocused()
    await calendarIcon.click()
    await expect(dialog.getByRole('button', { name: '29 February 2028', exact: true })).toBeFocused()
    await page.keyboard.press('ArrowRight')
    await expect(dialog.getByRole('button', { name: '1 March 2028', exact: true })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByLabel('Date', { exact: true })).toHaveValue('2028-03-01')
    await calendarIcon.click()
    await dialog.getByLabel('Month', { exact: true }).selectOption('2')
    await dialog.getByLabel('Year', { exact: true }).fill('2029')
    await expect(dialog.getByRole('button', { name: '29 February 2029', exact: true })).toHaveCount(0)
    await dialog.getByLabel('Year', { exact: true }).fill('2028')
    await dialog.getByRole('button', { name: '29 February 2028', exact: true }).click()
    const clockIcon = page.getByRole('button', { name: 'Choose start time', exact: true })
    await clockIcon.click()
    dialog = page.getByRole('dialog', { name: 'Choose start time', exact: true })
    await expect(dialog.getByLabel('Hour', { exact: true })).toBeFocused()
    await dialog.getByLabel('Hour', { exact: true }).selectOption('23')
    await dialog.getByLabel('Minute', { exact: true }).selectOption('45')
    await dialog.getByRole('button', { name: 'Use time', exact: true }).click()
    await expect(page.getByLabel('Start time', { exact: true })).toHaveValue('23:45')
    await expect(clockIcon).toBeFocused()
    await clockIcon.click()
    await dialog.getByLabel('Hour', { exact: true }).selectOption('10')
    await page.keyboard.press('Escape')
    await expect(page.getByLabel('Start time', { exact: true })).toHaveValue('23:45')
    await expect(clockIcon).toBeFocused()
    await calendarIcon.click()
    await page.getByRole('dialog').getByLabel('Year', { exact: true }).press('Enter')
    await expect(page.getByRole('dialog', { name: 'Choose date', exact: true })).toBeVisible()
    expect(creates).toBe(0)
    await page.getByRole('dialog').getByRole('button', { name: 'Close dialog', exact: true }).click()
    expect(creates).toBe(0)
    await page.getByLabel('Add an end time', { exact: true }).check()
    await page.getByRole('button', { name: 'Open calendar for end date', exact: true }).click()
    dialog = page.getByRole('dialog', { name: 'Choose end date', exact: true })
    await dialog.getByRole('button', { name: 'Next month', exact: true }).click()
    await dialog.getByRole('button', { name: '1 March 2028', exact: true }).click()
    await page.getByRole('button', { name: 'Choose end time', exact: true }).click()
    dialog = page.getByRole('dialog', { name: 'Choose end time', exact: true })
    await dialog.getByLabel('Hour', { exact: true }).selectOption('00')
    await dialog.getByLabel('Minute', { exact: true }).selectOption('15')
    await dialog.getByRole('button', { name: 'Use time', exact: true }).click()
    await page.getByLabel('Set a registration deadline', { exact: true }).check()
    await page.getByRole('button', { name: 'Open calendar for deadline date', exact: true }).click()
    dialog = page.getByRole('dialog', { name: 'Choose deadline date', exact: true })
    await dialog.getByRole('button', { name: '28 February 2028', exact: true }).click()
    await page.getByRole('button', { name: 'Choose deadline time', exact: true }).click()
    dialog = page.getByRole('dialog', { name: 'Choose deadline time', exact: true })
    await dialog.getByLabel('Hour', { exact: true }).selectOption('22')
    await dialog.getByLabel('Minute', { exact: true }).selectOption('00')
    await dialog.getByRole('button', { name: 'Use time', exact: true }).click()
    await page.getByLabel('Start time', { exact: true }).fill('22:30')
    for (const width of [360, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 900 })
      await calendarIcon.click()
      await expect(page.getByRole('dialog', { name: 'Choose date', exact: true })).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
      if (width === 360 || width === 1440) await page.screenshot({ path: `test-results/${engine}-calendar-${width}.png`, animations: 'disabled' })
      await page.keyboard.press('Escape')
    }
    await clockIcon.click()
    await page.screenshot({ path: `test-results/${engine}-time-picker.png`, animations: 'disabled' })
    await page.keyboard.press('Escape')
    const saving = page.waitForResponse(response => response.url().endsWith('/api/activities') && response.request().method() === 'POST')
    await page.getByRole('button', { name: 'Save draft', exact: true }).click()
    const stored = await (await saving).json()
    expect(stored.dateTime).toBe('2028-02-29T15:30:00.000Z')
    expect(stored.endDateTime).toBe('2028-02-29T17:15:00.000Z')
    expect(stored.registrationDeadline).toBe('2028-02-28T15:00:00.000Z')
    expect(creates).toBe(1)
    expect(await page.evaluate(() => (window as unknown as { nativePickerCalls: number }).nativePickerCalls)).toBe(0)
    expect(browserErrors).toEqual([])
  } finally { await context.close() }
}

test('calendar and clock icons select and persist all schedule fields in Chromium without native picker UI', async ({ browser }) => {
  await verifyPickers(browser, 'chromium')
})

test('calendar and clock icons select and persist all schedule fields in WebKit without native picker UI', async () => {
  const browser = await webkit.launch()
  try { await verifyPickers(browser, 'webkit') } finally { await browser.close() }
})
